create table design (
    id          bigint generated by default as identity primary key,
    name        varchar(100) not null,
    -- The principal name the design belongs to (the subject under OIDC), and the name to show.
    owner       varchar(255) not null,
    owner_name  varchar(255),
    shared      boolean      not null default false,
    -- The style as JSON, images included as data URLs, so a design can run to a few megabytes.
    -- An unbounded varchar rather than text or a CLOB: both H2 and PostgreSQL accept it, and
    -- Hibernate validates it as an ordinary string column on both.
    style       varchar      not null,
    created_at  timestamp with time zone not null,
    updated_at  timestamp with time zone not null
);

create index idx_design_owner on design (owner);
create index idx_design_shared on design (shared);
