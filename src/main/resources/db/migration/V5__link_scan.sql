-- One row per redirect that resolved to a destination, for the stats endpoint.
--
-- Deliberately coarse: no IP address and no user agent are stored, only what the stats show.
-- The device class and the bot flag are derived from the User-Agent when the scan is recorded,
-- and the referrer is reduced to its host.
create table link_scan (
    id            bigint generated by default as identity primary key,
    link_id       bigint      not null,
    scanned_at    timestamp with time zone not null,
    -- The UTC calendar day of scanned_at. Stored rather than derived because date truncation is
    -- spelled differently in H2 and PostgreSQL, and grouping on a plain column works on both.
    scanned_on    date        not null,
    device        varchar(16) not null,
    bot           boolean     not null,
    referrer_host varchar(255),
    -- The app only soft deletes links, so the cascade never fires in normal use; it lets a
    -- hard delete (by hand, or a test clearing the table) take the link's scans with it.
    constraint fk_link_scan_link foreign key (link_id) references short_link (id) on delete cascade
);

create index idx_link_scan_link_day on link_scan (link_id, scanned_on);
create index idx_link_scan_scanned_on on link_scan (scanned_on);
