create table short_link (
    id          bigint generated by default as identity primary key,
    code        varchar(16)   not null,
    target_url  varchar(2048) not null,
    created_at  timestamp with time zone not null,
    expires_at  timestamp with time zone,
    hit_count   bigint        not null default 0,
    last_hit_at timestamp with time zone,
    -- Soft delete: a printed code that is removed should answer 410 Gone rather than 404,
    -- which would look like a typo in the address.
    deleted_at  timestamp with time zone,
    constraint uq_short_link_code unique (code)
);

create index idx_short_link_created_at on short_link (created_at);
